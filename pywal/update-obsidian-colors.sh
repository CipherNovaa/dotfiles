#!/bin/bash
# update-obsidian-colors.sh — generate a pywal CSS snippet for the Obsidian vault.
# Obsidian hot-reloads snippet file changes, so once "pywal" is enabled in
# Settings -> Appearance -> CSS snippets, palette changes apply live.

COLORS="$HOME/.cache/wal/colors.json"
# Your vault: export OBSIDIAN_VAULT=... (or edit the default below).
VAULT="${OBSIDIAN_VAULT:-$HOME/Documents/Obsidian Vault}"
# Graph colour groups (Obsidian search syntax). The graph is split into two halves
# that get the wallpaper's two most-contrasting colours; point these at whatever
# split is meaningful in your vault (folders, tags...).
export OBSIDIAN_GRAPH_A="${OBSIDIAN_GRAPH_A:-tag:#ai}"
export OBSIDIAN_GRAPH_B="${OBSIDIAN_GRAPH_B:--tag:#ai}"
export OBSIDIAN_GRAPH_FILTER="${OBSIDIAN_GRAPH_FILTER:--path:Templates -path:Attachments}"
SNIPDIR="$VAULT/.obsidian/snippets"
APP="$VAULT/.obsidian/appearance.json"
GRAPH="$VAULT/.obsidian/graph.json"

[ -f "$COLORS" ] || exit 0
[ -d "$VAULT/.obsidian" ] || exit 0
command -v jq >/dev/null 2>&1 || exit 0
mkdir -p "$SNIPDIR"

g() { jq -r "$1" "$COLORS"; }
bg=$(g '.special.background'); fg=$(g '.special.foreground')
c0=$(g '.colors.color0'); c1=$(g '.colors.color1'); c4=$(g '.colors.color4')
c5=$(g '.colors.color5'); c8=$(g '.colors.color8')

# Signature accent: fcal + UI accents follow the wallpaper's DOMINANT colourful hue
# instead of the raw color4 slot. pywal often lands color4 on a pink/warm OUTLIER,
# so on a purple wallpaper fcal went pink while the graph (which selects *prominent*
# colours) correctly read purple. SIG = the most-saturated prominent palette colour,
# deepened, at a readable lightness; SIG_DARK = the same hue, darker (borders/hover).
# Greyscale wallpaper → stays a neutral grey (no fake tint), same as the graph.
read SIG SIG_DARK < <(python3 - "$COLORS" <<'PY'
import sys, json, colorsys
try:
    cols = json.load(open(sys.argv[1]))["colors"]
except Exception:
    print("#8a6b79 #6a5970"); sys.exit(0)
def rgbf(hx): hx = hx.lstrip('#'); return tuple(int(hx[i:i+2], 16) / 255 for i in (0, 2, 4))
def lum(hx): r, g, b = rgbf(hx); return 0.299 * r + 0.587 * g + 0.114 * b
def hls(hx): return colorsys.rgb_to_hls(*rgbf(hx))
pal = [c for c in (cols.get(f"color{i}") for i in range(16)) if c]
prom = [c for c in pal if hls(c)[2] >= 0.15 and lum(c) >= 0.12]
if len(prom) >= 2:                                             # genuinely colourful wallpaper
    sig = max(prom, key=lambda c: (round(hls(c)[2], 3), lum(c)))  # most saturated (tie→lighter)
    h, l, s = hls(sig)
    # Gentle boost only. The old `s * 2.0` + forced L=0.55 turned a MUTED wallpaper hue
    # into a neon accent (a terracotta #9A613F became a bright #ec742c orange,
    # when the wallpaper had zero bright orange). Keep the wallpaper's own
    # character: nudge saturation up a little (pywal washes colours out), and take the
    # accent's lightness from the SOURCE colour — only clamped into a readable band so
    # a very dark hue stays visible and a very light one doesn't wash out. A muted
    # wallpaper → muted accent; an already-vivid wallpaper (high S) → still vivid.
    s = min(1.0, s * 1.15)
    L_main = min(0.60, max(0.46, l))
else:
    # Greyscale / B&W wallpaper: pywal often injects ONE faint warm/pink swatch, and
    # amplifying its saturation turned the accent pink. Require ≥2 saturated colours to
    # call it "coloured"; otherwise force a NEUTRAL grey (matches the graph's logic).
    h, s, L_main = 0.0, 0.0, 0.55
def hexl(L):
    r, g, b = colorsys.hls_to_rgb(h, L, s)
    return "#%02x%02x%02x" % (round(r * 255), round(g * 255), round(b * 255))
print(hexl(L_main), hexl(max(0.30, L_main - 0.13)))
PY
)
[ -n "$SIG" ] || { SIG="$c4"; SIG_DARK="$c5"; }   # fallback to raw slots if compute fails

# NOTE: this pairs with the bare `pywal-generated-theme` (which only reads
# Obsidian's STANDARD vars). Do NOT switch cssTheme to Minimal — Minimal routes
# the tab bar/titlebar through its own --bg2/--frame-background indirection, which
# ignores these vars and leaves the chrome stuck grey. Bare theme + this snippet =
# the whole UI (incl. tab bar) follows the wallpaper. 
cat > "$SNIPDIR/pywal.css" <<EOF
/* Generated by update-obsidian-colors.sh — pywal palette */
.theme-dark, .theme-light {
  --background-primary:        $bg;
  --background-primary-alt:    $c0;
  --background-secondary:      $c0;
  --background-secondary-alt:  $bg;
  --titlebar-background:       $c0;
  --titlebar-background-focused: $c0;
  --text-normal:               $fg;
  --text-muted:                $c8;
  --text-faint:                $c8;
  --text-accent:               $SIG;
  --text-accent-hover:         $SIG_DARK;
  --interactive-accent:        $SIG;
  --interactive-accent-hover:  $SIG_DARK;
  --interactive-normal:        $c0;
  --background-modifier-border: $c1;
}

/* Full Calendar events → pywal accent, LIVE. The plugin's own data.json colour
   only applies on an Obsidian restart; this snippet hot-reloads, so events
   re-theme the instant the wallpaper changes. */
.fc .fc-event, .fc .fc-event-main, .fc-daygrid-event, .fc-daygrid-event-harness,
.fc-timegrid-event, .fc-timegrid-event .fc-event-main, .fc-list-event td {
  background-color: $SIG !important;
  border-color: $SIG_DARK !important;
  color: $bg !important;
}
.fc-daygrid-event-dot { border-color: $SIG !important; }
EOF

# Full Calendar events → follow pywal (was a fixed pink #8A6B79). FC stores the
# calendar-source colour in data.json and re-reads it live.
FC="$VAULT/.obsidian/plugins/obsidian-full-calendar/data.json"
if [ -f "$FC" ]; then
  python3 - "$FC" "$SIG" <<'PY'
import sys, json
fc, color = sys.argv[1], sys.argv[2]
try:
    d = json.load(open(fc))
    changed = False
    for src in d.get("calendarSources", []):
        if src.get("color") != color:
            src["color"] = color; changed = True
    if changed:
        json.dump(d, open(fc, "w"), indent=2)
except Exception:
    pass
PY
fi

# Ensure the snippet is enabled in appearance.json (preserve everything else).
python3 - "$APP" <<'PY'
import sys, json, os
p = sys.argv[1]
try:
    with open(p) as f:
        d = json.load(f)
except Exception:
    d = {}
snips = d.get("enabledCssSnippets", [])
changed = False
for s in ("pywal",):
    if s not in snips:
        snips.append(s); changed = True
if changed:
    d["enabledCssSnippets"] = snips
    with open(p, "w") as f:
        json.dump(d, f, indent=2)
PY

# 3. Recolor the graph as a two-sided duality (the "yin-yang"): group A (e.g. notes
#    written by agents/tools) in one pywal hue, group B (your own notes) in the other.
#    Groups come from OBSIDIAN_GRAPH_A / OBSIDIAN_GRAPH_B above.
#    Base hue = the most-saturated pywal slot (meaningful even on near-greyscale
#    palettes), forced vivid; the COOLER of {hue, complement} goes to the machine
#    side, the warmer to the human side -> reads intuitively on any wallpaper.
#    Force tuning preserved; we only touch colorGroups + a few display flags.
GRAPH_OUT=$(python3 - "$COLORS" "$GRAPH" <<'PY'
import sys, json, colorsys, os
colors_path, graph_path = sys.argv[1], sys.argv[2]
try:
    cols = json.load(open(colors_path)).get("colors", {})
except Exception:
    sys.exit(0)

def _rgbf(hx):
    hx = hx.lstrip("#"); return tuple(int(hx[i:i+2], 16) / 255 for i in (0, 2, 4))
def _int(r, g, b):
    return (round(r*255) << 16) | (round(g*255) << 8) | round(b*255)
def _cdist(a, b):
    d = abs(a - b) % 1.0; return min(d, 1 - d)

# Pick the TWO MOST-CONTRASTING actual pywal colours (NOT a forced-vivid hue), so
# the yin-yang follows the wallpaper: a colourful wallpaper → two vivid opposites,
# a black/white wallpaper → its own light/dark tones (no fake red/blue).
def _lum(hx):
    r, g, b = _rgbf(hx); return 0.299 * r + 0.587 * g + 0.114 * b
def _dist(a, b):                                    # redmean perceptual distance
    ra, ga, ba = _rgbf(a); rb, gb, bb = _rgbf(b)
    rm = (ra + rb) / 2; dr = ra - rb; dg = ga - gb; db = ba - bb
    return ((2 + rm) * dr * dr + 4 * dg * dg + (3 - rm) * db * db) ** 0.5

def _hls(hx): return colorsys.rgb_to_hls(*_rgbf(hx))

pal = [c for c in (cols.get(f"color{i}") for i in range(16)) if c] or ["#888888", "#cccccc"]
# "prominent" = colours with real saturation (exclude washed greys + the near-black bg).
prom = [c for c in pal if _hls(c)[2] >= 0.15 and _lum(c) >= 0.12]
greyscale = len(prom) < 2                          # <2 saturated colours → treat as B&W
if greyscale:                                      # greyscale wallpaper → use its own tones
    prom = [c for c in pal if _lum(c) >= 0.14] or pal
# CONTRAST = the wallpaper's own LIGHTEST vs DARKEST prominent colour. ONLY wallpaper
# colours — no complement, no invented hues.
light = max(prom, key=_lum)                                          # → your notes (human)
dark  = min(prom, key=lambda c: (round(_lum(c), 3), -_hls(c)[2]))    # darkest (tie→more saturated) → AI
# keep each colour's own HUE; DEEPEN saturation (they were washed out) and keep the
# dark one visible against the black canvas.
def _deepen(hx, floor_l):
    h, l, s = _hls(hx)
    if greyscale:                         # B&W wallpaper → neutral grey, never amplify a
        s = 0.0                           # faint pywal tint into pink
    elif s > 0.06:                        # nudge real colours up for canvas visibility, but
        s = min(1.0, s * 1.6)             # gently — the old ×2.6 neon-ified muted wallpapers
    return colorsys.hls_to_rgb(h, max(floor_l, l), s)
human_rgb   = _deepen(dark,  0.34)   # your notes (the majority) → darkest prominent
machine_rgb = _deepen(light, 0.55)   # AI side → lightest prominent
def col(rgbf):
    return {"a": 1, "rgb": _int(*rgbf)}

groups = [
    {"query": os.environ["OBSIDIAN_GRAPH_A"], "color": col(machine_rgb)},
    {"query": os.environ["OBSIDIAN_GRAPH_B"], "color": col(human_rgb)},
]
try:
    g = json.load(open(graph_path))
except Exception:
    g = {}
old_rgb = [grp.get("color", {}).get("rgb") for grp in g.get("colorGroups", [])]
new_rgb = [grp["color"]["rgb"] for grp in groups]
g["colorGroups"] = groups
g["showAttachments"] = False
g["showTags"] = False
g["search"] = os.environ["OBSIDIAN_GRAPH_FILTER"]
with open(graph_path, "w") as f:
    json.dump(g, f, indent=2)
# tell the shell whether the graph colours actually changed
print("GRAPH_CHANGED" if old_rgb != new_rgb else "GRAPH_SAME")
PY
)

# The graph is canvas-drawn: Obsidian reads graph.json ONLY at startup, so unlike the
# CSS snippet (which hot-reloads live) recoloring the graph needs an app reload. When
# the colorGroups actually changed AND Obsidian is running, tell it to reload so the
# graph repaints with the new palette ~1s after a wallpaper change = effectively dynamic.
#
# Mechanism: Obsidian has NO default reload hotkey and disables Chromium's Ctrl+R, so
# `app:reload` is bound to Ctrl+Shift+R in .obsidian/hotkeys.json (which syncs across
# devices). We deliver that shortcut to the obsidian window WITHOUT stealing focus via
# Hyprland's send_shortcut dispatcher — but this Hyprland uses a Lua IPC, so `hyprctl
# dispatch` mangles the args; we write the raw command straight to the Hyprland socket.
# Best-effort; never fails the script.
# Detect a running Obsidian across BOTH packagings: the AppImage (comm=obsidian,
# e.g. desktop) and the native/electron package (comm=electron, cmdline
# .../obsidian/app.asar, e.g. laptop). Matching `obsidian/app.asar` deliberately
# does NOT self-match this script (update-obsidian-colors.sh), so no false positive.
_obsidian_running() { pgrep -x obsidian >/dev/null 2>&1 || pgrep -f 'obsidian/app\.asar' >/dev/null 2>&1; }
# Reload Obsidian on BOTH machines so the graph re-themes (incl. "Colors Only").
# The reload used to yank focus on the laptop: native-Wayland electron Obsidian
# self-focuses ~1–2.5s after the reload, which Hyprland can't suppress. FIX = run
# Obsidian under XWayland (--ozone-platform=x11, like the desktop AppImage; set on the
# laptop's SUPER+N launch). The focus-bounce watcher below stays as a backstop. 2026-07-13.
if echo "$GRAPH_OUT" | grep -q GRAPH_CHANGED && _obsidian_running \
   && [ -n "$HYPRLAND_INSTANCE_SIGNATURE" ]; then
    _HYPRSOCK="${XDG_RUNTIME_DIR:-/run/user/$(id -u)}/hypr/$HYPRLAND_INSTANCE_SIGNATURE/.socket.sock"
    [ -S "$_HYPRSOCK" ] && python3 - "$_HYPRSOCK" <<'PY' 2>/dev/null || true
import socket, sys, json, time
sock = sys.argv[1]
def cmd(c):
    s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    s.connect(sock); s.sendall(c.encode())
    buf = b""
    while True:
        ch = s.recv(65536)
        if not ch:
            break
        buf += ch
    s.close(); return buf
def active():
    d = json.loads(cmd("j/activewindow") or b"{}")
    return (d.get("address") or ""), (d.get("class") or "").lower()
try:
    # Keep the wallpaper swap from yanking you into Obsidian. The reload itself can
    # pull focus two ways depending on the machine: send_shortcut can grab it instantly,
    # and the electron Obsidian (laptop) re-focuses itself ~1s later when its reload
    # finishes. So: remember who was focused, fire the reload, then WATCH for ~1.8s and
    # bounce focus back whenever Obsidian steals it. No-op when nothing steals (e.g. the
    # AppImage desktop never does). hl.dsp.focus({window="address:…"}) is the only
    # focus-by-window primitive this Lua-Hyprland exposes.
    prev_addr, prev_cls = active()
    cmd('dispatch hl.dsp.send_shortcut({ mods = "CTRL SHIFT", key = "R", window = "class:obsidian" })')
    if prev_addr and prev_addr != "0x0" and "obsidian" not in prev_cls:
        deadline = time.time() + 1.8
        while time.time() < deadline:
            time.sleep(0.2)
            cur_addr, cur_cls = active()
            if "obsidian" in cur_cls and cur_addr != prev_addr:
                cmd('dispatch hl.dsp.focus({ window = "address:%s" })' % prev_addr)  # steal → bounce back
            elif cur_addr and cur_addr != prev_addr:
                break   # the user deliberately moved to some other window — stop fighting
except Exception:
    pass
PY
fi
