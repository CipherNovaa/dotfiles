#!/usr/bin/env python3
"""
zen-pywal — theme Zen Browser's chrome from the current pywal palette.

Zen ignores the standard Firefox `theme` API (so pywalfox has no visible effect
on its custom chrome — verified 2026-07-14). Instead Zen derives its whole UI
from its own CSS custom properties, chiefly `--zen-primary-color` (accent) and
`--zen-main-browser-background`. This writes those (and a few companions) from
~/.cache/wal/colors.json into the Zen profile's chrome/zen-pywal.css, which
userChrome.css @imports. Called by the wallpaper picker so Zen follows the
wallpaper like every other app.

Note: userChrome.css is read at browser startup, so a colour change applies to
Zen on its next launch (no live reload yet). Idempotent + safe to re-run.
"""
import json, os, sys, configparser, colorsys

HOME = os.path.expanduser("~")
COLORS = os.path.join(HOME, ".cache/wal/colors.json")
# Zen has used both roots across versions and migrates between them, leaving a
# stale copy behind. Never assume one: pick the profile that's actually live.
ZEN_ROOTS = [os.path.join(HOME, ".zen"), os.path.join(HOME, ".config/zen")]


def hex_to_rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def saturation_value(h):
    r, g, b = (c / 255 for c in hex_to_rgb(h))
    hh, l, s = colorsys.rgb_to_hls(r, g, b)
    return s, l


def pick_accent(colors):
    """Most saturated palette colour (colors 1..6), tie-broken by mid-lightness."""
    best, best_score = colors["color4"], -1
    for i in range(1, 7):
        c = colors.get(f"color{i}")
        if not c:
            continue
        s, l = saturation_value(c)
        # favour saturated, mid-bright colours for a usable accent
        score = s * (1 - abs(l - 0.55))
        if score > best_score:
            best, best_score = c, score
    return best


def default_profile_in(root):
    """The profile profiles.ini marks as default under `root`, if any."""
    ini = os.path.join(root, "profiles.ini")
    if not os.path.isfile(ini):
        return None
    cfg = configparser.ConfigParser()
    cfg.read(ini)
    # Prefer the Install section's Default= (the actively-used profile)
    for sect in cfg.sections():
        if sect.startswith("Install") and cfg.has_option(sect, "Default"):
            full = os.path.join(root, cfg.get(sect, "Default"))
            if os.path.isdir(full):
                return full
    # Fallback: any [ProfileN] with Default=1, else first real profile
    fallback = None
    for sect in cfg.sections():
        if sect.startswith("Profile") and cfg.has_option(sect, "Path"):
            full = os.path.join(root, cfg.get(sect, "Path"))
            if not os.path.isdir(full):
                continue
            if cfg.get(sect, "Default", fallback="0") == "1":
                return full
            fallback = fallback or full
    return fallback


def liveness(profile):
    """How recently this profile was actually browsed in (places.sqlite mtime)."""
    places = os.path.join(profile, "places.sqlite")
    try:
        return os.path.getmtime(places)
    except OSError:
        return -1


def find_default_profile():
    """The live Zen profile across both possible roots.

    A migrated-away root keeps a full-looking stale profile (same extensions,
    same size), so the default flag alone picks the wrong one. Break the tie on
    places.sqlite mtime — only the profile Zen actually runs gets browsed in.
    """
    cands = [p for p in (default_profile_in(r) for r in ZEN_ROOTS) if p]
    if not cands:
        return None
    return max(cands, key=liveness)


CSS_TEMPLATE = """/* Generated by ~/scripts/system/zen-pywal.py — do not edit by hand.
 * Regenerated on every wallpaper change. Themes Zen's chrome from pywal. */
:root {{
  --zen-primary-color: {accent} !important;
  --zen-colors-primary: {accent} !important;
  --zen-colors-secondary: {c8} !important;
  --zen-colors-tertiary: {c8} !important;
  --zen-colors-primary-foreground: {fg} !important;

  --zen-main-browser-background: {bg} !important;
  --zen-main-browser-background-toolbar: {bg} !important;

  --zen-toolbar-element-bg: color-mix(in srgb, {fg} 8%, transparent) !important;
  --zen-colors-border: color-mix(in srgb, {fg} 14%, transparent) !important;

  /* Standard Firefox chrome vars so page-adjacent surfaces match */
  --toolbar-bgcolor: {bg} !important;
  --toolbar-color: {fg} !important;
  --lwt-accent-color: {bg} !important;
  --toolbox-textcolor: {fg} !important;
}}
"""

USERCHROME_IMPORT = '@import url("zen-pywal.css");'


def ensure_userchrome(chrome_dir):
    uc = os.path.join(chrome_dir, "userChrome.css")
    line = USERCHROME_IMPORT
    if os.path.isfile(uc):
        with open(uc) as f:
            body = f.read()
        if "zen-pywal.css" in body:
            return
        with open(uc, "w") as f:
            f.write(line + "\n" + body)
    else:
        with open(uc, "w") as f:
            f.write("/* Zen userChrome — pywal import kept at top. */\n" + line + "\n")


def ensure_pref(profile):
    """Zen needs legacy userChrome stylesheets enabled. Persist via user.js."""
    uj = os.path.join(profile, "user.js")
    pref = 'user_pref("toolkit.legacyUserProfileCustomizations.stylesheets", true);'
    existing = ""
    if os.path.isfile(uj):
        with open(uj) as f:
            existing = f.read()
    if "legacyUserProfileCustomizations.stylesheets" not in existing:
        with open(uj, "a") as f:
            if existing and not existing.endswith("\n"):
                f.write("\n")
            f.write(pref + "\n")


def main():
    if not os.path.isfile(COLORS):
        print("zen-pywal: no colors.json", file=sys.stderr)
        return 1
    with open(COLORS) as f:
        w = json.load(f)
    colors = w["colors"]
    bg = w["special"]["background"]
    fg = w["special"]["foreground"]
    accent = pick_accent(colors)
    css = CSS_TEMPLATE.format(accent=accent, c8=colors.get("color8", fg), fg=fg, bg=bg)

    profile = find_default_profile()
    if not profile:
        print("zen-pywal: no Zen profile found (is Zen installed/run once?)", file=sys.stderr)
        return 1
    chrome_dir = os.path.join(profile, "chrome")
    os.makedirs(chrome_dir, exist_ok=True)
    with open(os.path.join(chrome_dir, "zen-pywal.css"), "w") as f:
        f.write(css)
    ensure_userchrome(chrome_dir)
    ensure_pref(profile)
    print(f"zen-pywal: accent={accent} bg={bg} -> {chrome_dir}/zen-pywal.css")
    return 0


if __name__ == "__main__":
    sys.exit(main())
