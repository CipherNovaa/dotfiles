#!/bin/bash
# update-hyprlock-colors.sh — emit hyprlock color variables from pywal.
# hyprlock.conf does `source = ~/.cache/wal/hyprlock-colors.conf` and references
# these vars, so the lock screen uses the current palette on its next launch.

COLORS="$HOME/.cache/wal/colors.json"
OUT="$HOME/.cache/wal/hyprlock-colors.conf"
[ -f "$COLORS" ] || exit 0
command -v jq >/dev/null 2>&1 || exit 0

g() { local v; v=$(jq -r "$1" "$COLORS"); echo "${v#\#}"; }

bg=$(g '.special.background')
fg=$(g '.special.foreground')
c1=$(g '.colors.color1')
c2=$(g '.colors.color2')
c3=$(g '.colors.color3')
c5=$(g '.colors.color5')
c8=$(g '.colors.color8')

cat > "$OUT" <<EOF
# Generated by update-hyprlock-colors.sh — do not edit by hand
\$accent     = rgba(${c3}aa)
\$accent2    = rgba(${c5}cc)
\$bg         = rgba(${bg}cc)
\$fg         = rgba(${fg}ff)
\$ok         = rgba(${c2}ff)
\$err        = rgba(${c1}ff)
\$caps       = rgba(${c3}ff)
# bare hex (no leading #) — referenced as foreground="##\$muted_hex" in a pango span
\$muted_hex  = ${c8}
EOF
